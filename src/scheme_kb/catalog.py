def get_all_schemes() -> list[dict[str, Any]]:
    """Return all schemes as dictionaries."""
    return [s.__dict__ for s in SCHEMES_CATALOG]


def get_scheme_by_id(scheme_id: str) -> dict[str, Any] | None:
    """Lookup a single scheme by ID."""
    for s in SCHEMES_CATALOG:
        if s.id == scheme_id:
            return s.__dict__
    return None
